// ---------------------------------------------------------------------------
// WHAT A SHOT DOES, AND WHERE EACH PART OF IT LIVES
// ---------------------------------------------------------------------------
// Three systems here used to be invented rather than read. They are Epic's now:
//
//   1. THE GUN ANIMATES. UE1 view weapons are baked vertex animations — PlayAnim('Shoot',
//      rate) on a shot, 'Select' on bring-up, an idle loop ('Sway' at 0.2x for the
//      Enforcer, with a 4% chance of a one-shot 'Twiddle' each time it comes round),
//      'Down' on the way out. The old build had a static mesh and faked motion by rotating
//      the whole entity. See view-weapon-anim.js; the clip names and rates come from the
//      weapon manifest's `view.anims`.
//
//   2. THE VIEW SHAKES, THE AIM DOES NOT. UT99 has no camera recoil at all: the crosshair
//      never moves when you fire. PlayerPawn.ShakeView rolls the view and jolts the eye
//      vertically, cosmetically. See player/view-shake.js; the controller owns both
//      transforms it is written to, and this system only calls player.shake(spec).
//
//   3. THE MUZZLE FLASH IS 2D, AND MOSTLY ABSENT. Engine.Weapon.RenderOverlays draws it
//      with Canvas.DrawIcon — a screen-space icon, not geometry — and only the Enforcer
//      and the Sniper Rifle have one. The old procedural quad plus point light are gone;
//      the HUD draws the icon and the screen tint (PlayerPawn.ClientInstantFlash) instead.
//
// Every number those three need is per weapon and comes out of src/shared/weapons.js,
// which is GENERATED from Epic's own classes. Each read below is defensive: the manifest
// is regenerated by a separate pipeline and a field that is not there yet must degrade to
// the old, quiet behaviour rather than throw in the middle of a shot.

// ---------------------------------------------------------------------------
// WHERE A HELD WEAPON SITS
// ---------------------------------------------------------------------------
// Epic's, end to end, since 2026-09-05. Engine.Inventory.CalcDrawOffset places the view
// weapon's ORIGIN at PlayerViewOffset from the eye and draws the mesh about it at its own
// scale; the corner of the screen a gun sits in is then simply where its mesh is authored
// relative to that origin. Reproducing it needs the offset and the mesh scaled by the
// SAME factor: scaling a rigid layout uniformly about the eye leaves its projection
// unchanged, so that one factor is free, and it is spent on the near plane — the camera
// clips at 0.05 m (engine/game.js) and Epic's Enforcer, 12 cm long with its origin 8 cm
// from the eye, would lose its grip to it at 1x.
//
// A note on the number UnrealScript shows, because it misled this file for a week.
// CalcDrawOffset reads `(0.9 / FOVAngle) * PlayerViewOffset`, which at FOV 90 is a
// hundredth of a UU and puts the eye INSIDE every mesh — that was tried, in the browser,
// and it does. PlayerViewOffset taken as plain Unreal Units puts all six weapons where
// UT99 has them (Enforcer low left, rifles low right with the receiver's side showing and
// the barrel on the crosshair), and lands within a few centimetres of the position the
// previous build had fitted by eye. Whatever the engine does with that factor, the raw
// offset is the number that draws the picture, and it is what is used here.
const VIEW = {
  // The uniform factor above. Appearance-invariant: changing it moves nothing on screen,
  // only how far in front of the near plane the geometry lives (and how far it can poke
  // through a wall you stand against).
  MODEL_SCALE: 3.75,
};

// The LAST-RESORT held weapon, used only if the manifest ships a weapon with no view mesh
// at all. It is the floor pickup model at the scale and muzzle offset index.html carried
// before the view meshes existed — the barrel tip measured off the 247 vertices at
// z <= -10, in that mesh's own local units. Not decoration: it is what keeps a broken or
// half-regenerated src/shared/weapons.js from leaving the player empty-handed.
const FALLBACK = {
  SCALE: 0.025,
  MUZZLE_LOCAL: [0.2, 1.4, -10.7],
};

// Shared audio pool for weapon sounds
const WEAPON_POOL_SIZE = 4;
const isMobileDevice = /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(navigator.userAgent);
let weaponAudioIndex = 0;

// A pool PER WEAPON, keyed by the sound file. Every weapon used to share one
// assets/audio/fire.wav; each now plays what UT99 plays — the Enforcer's E_Shot, the
// Sniper's SniperFire, the Rocket Launcher's Ignite — and firing while an earlier shot
// is still ringing needs more than one element of each, which is what the pool is for.
const weaponAudioPools = new Map();

function poolFor(src) {
  if (isMobileDevice) return null;
  let pool = weaponAudioPools.get(src);
  if (pool) return pool;
  pool = [];
  for (let i = 0; i < WEAPON_POOL_SIZE; i++) {
    const a = new Audio(src);
    a.volume = 0.1;
    a.preload = "auto";
    pool.push(a);
  }
  weaponAudioPools.set(src, pool);
  return pool;
}

function playPooledWeaponSound(volume, src) {
  const pool = poolFor(src || ASSETS.fireSound);
  if (!pool) return;
  const a = pool[weaponAudioIndex % WEAPON_POOL_SIZE];
  weaponAudioIndex++;
  a.volume = volume;
  a.currentTime = 0;
  a.play().catch(() => {});
}

/**
 * Warm a weapon's pools so its first shot — and its bring-up — are not silent while the
 * files load. `selectSound` is the class's own SelectSound, played once when the weapon
 * comes up; it is read defensively because the manifest may not carry it yet.
 */
function warmSounds(id) {
  const spec = weapon(id);
  if (!spec) return;
  if (spec.sound) poolFor(spec.sound);
  if (spec.selectSound) poolFor(spec.selectSound);
}

/** Warm a weapon's pool so the first shot with it is not silent while the file loads. */
export function preloadWeaponSound(id) {
  warmSounds(id);
}

