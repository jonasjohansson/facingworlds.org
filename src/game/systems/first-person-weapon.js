// first-person-weapon.js — First-person weapon view and shooting
// The Enforcer is hitscan: every shot is a single instant trace from the camera against
// world geometry and player capsules, with the tracer drawn from the muzzle to whatever
// the trace hit. Nothing travels.
//
// Port of the A-Frame first-person-weapon component. What the A-Frame version expressed
// through the DOM is scene-graph and method calls here:
//
//   #view-shake        gone. The controller writes the shake to the camera and to
//                      game.player.gunRoot itself (player/controller.js says why the extra
//                      node existed); this system only ARMS it, through player.shake(spec).
//   #player-weapon     a THREE.Group `held` under gunRoot, with the sway on it, and one
//                      Group per slot under that. The slots carry each weapon's own
//                      PlayerViewOffset, so the sway moves the hand and the slots the guns.
//   gltf-model         assets.attachModel(slot, url), awaited. No model-loaded event.
//   el.__slotAnim      slot.userData.anim; el.__muzzleEl -> slot.userData.muzzle.
//   key/mouse handlers game.input.fireHeld, a level the update loop reads. The rising edge
//                      (which resets the burst counter) is detected here.
