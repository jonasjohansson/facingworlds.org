const DEG = Math.PI / 180;

export class FirstPersonWeapon {
  /**
   * @param {object} game the engine handle
   * @param {object} [opts] see DEFAULTS
   */
  constructor(game, opts = {}) {
    this.game = game;
    this.data = { ...DEFAULTS, ...opts };

    this.weapon = null;
    this.muzzlePosition = new THREE.Vector3();
    this.isFiring = false;
    this.lastFireTime = 0;
    this.killStreak = 0;
    this.lastKillTime = 0;
    this.spreeCount = 0;
    this._burstShots = 0;

    // ---- hitscan scratch vectors ----
    // The ray this system builds — origin, direction, and the basis and muzzle vectors it
    // is built from — is written into these instead of into fresh Vector3s per shot. The
    // trace itself still allocates: systems/hitscan.js returns a result object with its own
    // `point` and `normal` for every call, exactly as the A-Frame hitscan did. Firing is
    // rate-limited and this is the same garbage the old build made, so it is left alone.
    this._rayOrigin = new THREE.Vector3();
    this._rayDir = new THREE.Vector3();
    this._right = new THREE.Vector3();
    this._up = new THREE.Vector3();
    this._muzzleLocal = new THREE.Vector3();
    this._muzzleWorld = new THREE.Vector3();
    this._quat = new THREE.Quaternion();

    // ---- feel state ----
    this.crosshairBloom = 0;

    // The HUD owns both screen-space halves of a shot: the ClientInstantFlash tint and
    // the RenderOverlays muzzle icon. Taken as a reference here (and released in
    // dispose()) rather than looked up per shot.
    this.hud = getHud(game);
    this._screen = new THREE.Vector3(); // scratch for projecting the muzzle to the screen

    // ---- the scene graph ----
    // The hand: one node, under the node the controller writes the shake's roll and eye
    // lift to, with the sway on it. Every slot hangs off it, so a dual pair sways as one
    // piece — which is what two slots with identical sway settings did anyway.
    //
    // No gunRoot means no player controller: a stripped page or a test harness. The gun
    // then hangs off the camera and gets the primitive fallback below, exactly as the old
    // component did when index.html's #player-weapon was missing.
    this.hasPlayer = !!(game.player && game.player.gunRoot);
    this.held = new THREE.Group();
    this.held.name = "player-weapon";
    (this.hasPlayer ? game.player.gunRoot : game.camera).add(this.held);
    this.sway = new WeaponSway(game, this.held, { ...(this.data.sway || {}), rest: { x: 0, y: 0, z: 0 } });

    // Slot bookkeeping. `primarySlot` is what index.html called #player-weapon; the second
    // slot only exists once you are holding two Enforcers. Everything a slot needs at
    // runtime is parked on the node itself (userData.slotUrl / .anim / .muzzle) so a slot
    // is self-describing and a mid-load weapon switch cannot cross the wires between them.
    this.slots = [];
    this.primarySlot = null;
    this.secondSlot = null;
    this._loopingFire = false; // a LoopAnim'd fire clip (Shock, Ripper) is running

    // No kill flash. DrawFragCount's only feedback on a frag is the 3 s gold
    // sawtooth on the frag box plus its gold glow blob, both of which the HUD
    // already draws; ChallengeHUD has no screen-edge pulse anywhere.

    // Crosshair — Botpack.CHair1, the stock UT99 default (Engine.HUD Crosshair=0).
    //
    // It is a 64x64 GREYSCALE texture drawn at
    //     XScale  = ClipX < 512 ? 0.5 : max(1, int(0.1 + ClipX/640))
    //     XLength = 64 * XScale, centred at ((W-XLength)/2, (H-XLength)/2)
    // in 15 * CrosshairColor = 15 * (0,16,0) = (0,240,0) GREEN, STY_Translucent.
    // No outline, no glow, no bloom, and it does NOT move when you fire — the
    // only animation on it is a 0.4 s grow-to-2x-and-back after a PICKUP.
    //
    // The art is EXACTLY 16 lit texels, pixel-dumped from the shipped PNG: four
    // ticks per arm, the horizontal arm an exact mirror of the vertical, and NO
    // texel at (32,32) — the centre is hollow, so nothing sits on the point you
    // are aiming at. Drawn here as 1x1 rects in a 64-unit viewBox with
    // crispEdges, so the SVG lands on the same integer grid the
    // nearest-neighbour blit would.
    this.crosshair = document.createElement("div");
    this.crosshair.className = "ut-crosshair";
    this.crosshair.innerHTML =
      '<svg viewBox="0 0 64 64" shape-rendering="crispEdges" aria-hidden="true">' +
      // vertical arm, x = 32: rows 26, 28..30, 34..36, 38
      '<rect x="32" y="26" width="1" height="1"/>' +
      '<rect x="32" y="28" width="1" height="3"/>' +
      '<rect x="32" y="34" width="1" height="3"/>' +
      '<rect x="32" y="38" width="1" height="1"/>' +
      // horizontal arm, y = 32: the mirror of the vertical — cols 26, 28..30,
      // 34..36, 38
      '<rect x="26" y="32" width="1" height="1"/>' +
      '<rect x="28" y="32" width="3" height="1"/>' +
      '<rect x="34" y="32" width="3" height="1"/>' +
      '<rect x="38" y="32" width="1" height="1"/>' +
      "</svg>";
    document.body.appendChild(this.crosshair);
    this.crosshairPulse = 0; // seconds remaining of the 0.4 s pickup pulse
    this._onResize = () => this.updateCrosshair();
    window.addEventListener("resize", this._onResize);
    this.updateCrosshair();

    // Hitmarker — NOT A SOURCE BEHAVIOUR, kept deliberately and annotated the
    // way the reload blink and the TAB hint are. UT99 confirms a hit with the
    // victim's pain sound over a LAN link; this build is a browser peer game
    // where that sound may never arrive, so an 80 ms white X stands in for it.
    // A chunky X with a gold bloom, hidden by default. The two bars are
    // rotated by .ut-hitmarker i:first-child / :last-child in styles.css.
    this.hitmarker = document.createElement("div");
    this.hitmarker.className = "ut-hitmarker";
    this.hitmarker.appendChild(document.createElement("i"));
    this.hitmarker.appendChild(document.createElement("i"));
    document.body.appendChild(this.hitmarker);

    // Firing is a LEVEL read off engine/input.js — no key or mouse listeners here any
    // more. It owns the two rules the old handlers carried: KeyX and the left button both
    // set it, and the button only counts while the pointer is locked, so the click that
    // TAKES the lock does not put a shot into the floor. (KeyC's guarded swapCamera hook
    // is gone with them: there is no camera-swap implementation anywhere, and the hook
    // never called one.)

    // Create touch fire button for mobile devices
    this.createTouchFireButton();

    // Multi-kill announcement element (center screen). Same behaviour as before —
    // only the typography moved to styles.css (.ut-announce), where it now matches
    // the corner plates: heavy condensed caps, saturated glow, and a slam-in.
    this.announceEl = document.createElement("div");
    this.announceEl.className = "ut-announce ut-announce--multikill";
    document.body.appendChild(this.announceEl);

    // Spree announcement element (below multi-kill)
    this.spreeEl = document.createElement("div");
    this.spreeEl.className = "ut-announce ut-announce--spree";
    document.body.appendChild(this.spreeEl);

    // ---- dual Enforcers ----
    // UT99's second-Enforcer pickup: same gun twice, fired alternately, so the
    // rate doubles while each shot is individually worse. The SERVER grants this
    // (see server/server.js takePickup) and the network layer re-emits it; the
    // weapon never decides on its own that it has two guns.
    this.dual = false;
    // What we are holding. The SERVER decides — this only ever follows a loadout
    // message — and it drives both the model and the fire rate.
    this.weaponId = DEFAULT_WEAPON;
    // Warm the Enforcer's sounds at construction. Every other weapon's are warmed when it
    // is picked up; this one is never picked up, so without this the very first shot of a
    // session is silent while the file loads.
    warmSounds(DEFAULT_WEAPON);
    this.fireLeft = false; // which hand fires the next shot

    // A loadout change is the only local "you picked something up" signal the
    // network layer emits, so it is what drives the crosshair's pickup pulse.
    this._onLoadout = (e) => {
      this.setDual(!!(e.detail && e.detail.dual));
      if (e.detail && e.detail.weapon) this.setWeapon(e.detail.weapon);
      this.pulseCrosshair();
    };
    // Dying costs you the second gun, so the weapon has to hear about deaths too.
    this._onDeath = () => {
      this.setDual(false);
      // The weapon dies with you, as on the server. Back to the Enforcer everyone
      // spawns holding, so the model in your hands matches the damage you deal.
      this.setWeapon(DEFAULT_WEAPON);
      this.spreeCount = 0;
    };
    this._onHit = () => this.onLocalHit();
    this._onKill = (e) => this.onLocalKill(e);
    const events = game.events;
    this._off = [
      events.on("local-loadout", this._onLoadout),
      events.on("local-death", this._onDeath),
      events.on("local-hit", this._onHit),
      events.on("local-kill", this._onKill),
    ];

    this.setupWeapon();
  }

  // What A-Frame's `update()` hook did: health.js flips this on death and respawn.
  get enabled() {
    return this.data.enabled;
  }

  set enabled(value) {
    const on = !!value;
    if (on === this.data.enabled) return;
    this.data.enabled = on;
    if (on) this.setupWeapon();
    else this.removeWeapon();
  }

  update(dt, now) {
    // dt arrives in SECONDS, already clamped by the loop so a tab-switch stall cannot run
    // a whole animation out in one frame (engine/game.js MAX_DT).
    const nowSeconds = now / 1000;

    this.sway.update(dt);
    this.updateViewAnimations(dt, nowSeconds);
    this.decayCrosshairBloom(dt);

    // The trigger, as a level, with its own rising edge: the second and later shots of one
    // held trigger are REPEAT shots, and the counter that says so resets when the trigger
    // goes down, not when a shot lands.
    const held = !!(this.game.input && this.game.input.fireHeld);
    if (held && !this.isFiring) this._burstShots = 0;
    this.isFiring = held;

    if (!this.isFiring) return;

    // Cadence is the weapon's, not the system's default: a Sniper Rifle that fired
    // four times a second would be a different weapon wearing the same model.
    const rate = this.dual ? GAME_CONFIG.WEAPON.DUAL_FIRE_RATE : weapon(this.weaponId).fireRate;
    // Rates below one per second are real (the Sniper's 0.667, the Redeemer's 0.4); the
    // old Math.max(1, rate) here silently made every slow weapon a one-per-second gun.
    const minInterval = 1 / Math.max(0.05, rate);
    if (nowSeconds - this.lastFireTime < minInterval) return;
    // FinishAnim. UT99's fire states refire only once the fire animation has played out,
    // so a gun is never yanked back to its first frame mid-recoil. The Enforcer is the
    // one that bites: 'Shoot' runs 0.41 s against a 0.25 s interval, and cutting it every
    // shot was a measured 73 px snap per shot. Cadence waits for the clip too — which is
    // also exactly why UT99's Enforcer plays 'Shoot' once and the shorter 'shot2' after.
    if (this.fireClipBusy() > 0) return;

    this.lastFireTime = nowSeconds;
    // The second and later shots of one held trigger are REPEAT shots (PlayRepeatFiring).
    this._burstShots = (this._burstShots || 0) + 1;
    this.fireBullet();
  }

  setupWeapon() {
    // Already armed. Both the `enabled` setter and the constructor call this, and without
    // the guard a fresh page would run the whole bring-up twice — two Select animations
    // and two SelectSounds on top of each other in the first second of a match.
    if (!this.data.enabled || this.weapon) return;

    if (!this.hasPlayer) {
      console.warn("[first-person-weapon] No player gunRoot, creating fallback");
      this.createFallbackWeapon();
      return;
    }

    this.primarySlot = this._ensureSlot(0);
    this.weapon = this.primarySlot;
    this.weapon.visible = true;

    // Coming back from a death: the slots were hidden, not destroyed (see removeWeapon),
    // so refit is cheap — the model URLs have not changed, nothing reloads, and the only
    // real work is re-arming the Select animation and its sound.
    this.refitWeapons(true);
  }

  /** One weapon slot: a Group under the held node. Built on first need, then reused. */
  _ensureSlot(i) {
    if (this.slots[i]) return this.slots[i];
    const slot = new THREE.Group();
    slot.name = i === 0 ? "weapon-slot-primary" : "weapon-slot-second";
    // A-Frame set every entity's rotation order to YXZ (a-entity.js). All six weapons ship
    // rotationDeg [0,0,0] today, so it changes nothing — it is here so a manifest that
    // starts carrying Epic's RotOrigin composes its axes the way the old build did.
    slot.rotation.order = "YXZ";
    slot.visible = false;
    this.held.add(slot);
    this.slots[i] = slot;
    if (i === 1) this.secondSlot = slot;
    return slot;
  }

  /**
   * Where the tracer starts and where the 2D muzzle icon is drawn.
   *
   * Each slot carries its own barrel tip as a child node (built by dressSlot from the
   * manifest's `view.muzzleLocal`), so this is a world-matrix read rather than a constant.
   * The child inherits the slot's rotation AND its scale — including the negative x a
   * mirrored right-hand weapon has — which is what makes one stored point correct for
   * both a left-hand and a mirrored right-hand draw of the same mesh.
   */
  setupMuzzlePosition() {
    const slot = this.weapon;
    const muzzle = slot ? slot.userData.muzzle : null;

    if (muzzle) {
      // Safe to call mid-update, before the renderer has walked the graph for the frame:
      // three.js's getWorldPosition does its own updateWorldMatrix(true, false) up the
      // ancestors first, so this sees the position weapon-sway wrote this frame.
      muzzle.getWorldPosition(this.muzzlePosition);
      // fireBullet() re-reads this every shot, so log it once — a per-shot log both spams
      // the console and prints the same reused, mutated vector for every entry.
      if (!this._loggedMuzzle) {
        this._loggedMuzzle = true;
        console.log("[first-person-weapon] Muzzle position from slot:", this.muzzlePosition.toArray());
      }
      return;
    }

    // No slot, or no muzzle child yet: the camera's own offset, as before.
    const camera = this.game.camera;
    camera.getWorldPosition(this._muzzleWorld);
    this.muzzlePosition.copy(this.data.muzzleOffset);
    this.muzzlePosition.applyQuaternion(camera.getWorldQuaternion(this._quat));
    this.muzzlePosition.add(this._muzzleWorld);
    if (!this._loggedMuzzleFallback) {
      this._loggedMuzzleFallback = true;
      console.log("[first-person-weapon] Muzzle position fallback:", this.muzzlePosition.toArray());
    }
  }

  // -------------------------------------------------------------------------
  // WHAT IS IN YOUR HANDS
  // -------------------------------------------------------------------------

  /**
   * Put the right mesh, on the right side of the screen, in every slot.
   *
   * One entry point for all four things that can change it — spawn, a pickup, the second
   * Enforcer arriving or leaving, and a respawn — because they used to be three separate
   * code paths and the Enforcer was in none of them. That is why the gun you spawn with
   * could not animate: setWeapon() returned early for it (its `model` is null, since it
   * has no floor pickup) and index.html showed the pickup mesh, which has no clips.
   *
   * WHICH HAND. UT99 draws the single Enforcer in the LEFT hand — its view mesh, AutoML,
   * is modelled as a left-hand gun — and the five rifles on the right. The rifles are
   * ALSO authored as left-hand meshes, because UE1 mirrors the view weapon for a
   * right-handed player, so drawing them on the right means mirroring them here.
   *
   * @param {boolean} playSelect play the bring-up animation and its SelectSound
   */
  refitWeapons(playSelect) {
    if (!this.primarySlot) return;

    // A loadout change can arrive while the gun is PUT AWAY — dying emits local-death,
    // and this system's own handler answers it with setDual(false) + setWeapon(), which
    // lands after health.js has already disabled it and hidden the slots. Left unguarded
    // that refit would set `visible` back to true and play a bring-up sound over the death
    // screen. Respawn calls setupWeapon(), which refits again with the gun out.
    const show = this.data.enabled && !!this.weapon;
    if (!show) playSelect = false;

    const spec = weapon(this.weaponId);
    const view = spec && spec.view ? spec.view : null;
    // Absent `hand` means the manifest predates the handedness pass. "left" is the safe
    // default: it is the UNMIRRORED draw, i.e. exactly how every weapon looked before.
    const hand = view && view.hand === "right" ? "right" : "left";

    if (this.dual) {
      // Two Enforcers. UT99's second mesh (AutoMR) is a genuine RIGHT-hand model, so it
      // is drawn as-is; only if the manifest has no `dualModel` yet does the right gun
      // fall back to a mirror of the left one.
      const dualModel = view && view.dualModel ? view.dualModel : null;
      this.dressSlot(this.primarySlot, view, "right", !dualModel, dualModel || (view && view.model), playSelect, show);
      this.dressSlot(this._ensureSlot(1), view, "left", false, view && view.model, playSelect, show);
    } else {
      this.dressSlot(this.primarySlot, view, hand, hand === "right", view && view.model, playSelect, show);
      if (this.secondSlot) this.secondSlot.visible = false;
    }

    // SelectSound is the weapon class's own bring-up sound, and it is optional: the
    // manifest may not carry it, in which case the swap is silent as it was before.
    if (playSelect && spec && spec.selectSound) playPooledWeaponSound(0.1, spec.selectSound);
  }

  /**
   * Point one slot at one mesh, on one side of the screen.
   *
   * @param {THREE.Object3D} slot the slot node
   * @param {object|null} view the manifest's `view` block, or null
   * @param {"left"|"right"} side which side of the screen centre it is drawn on
   * @param {boolean} mirror negate scale.x — see below
   * @param {string|null} model the glTF URL to load
   * @param {boolean} playSelect run the bring-up animation once it is in
   * @param {boolean} show false while the gun is put away (dead / system disabled)
   */
  dressSlot(slot, view, side, mirror, model, playSelect, show) {
    // The fallback pickup mesh keeps the placement index.html gave it for years.
    const FALLBACK_POS = { x: 0.2, y: -0.3, z: -0.5 };
    const sign = side === "left" ? -1 : 1;

    let x = sign * FALLBACK_POS.x;
    let y = FALLBACK_POS.y;
    let z = FALLBACK_POS.z;
    let rot = [0, 0, 0];
    let scale = FALLBACK.SCALE;
    let muzzleLocal = FALLBACK.MUZZLE_LOCAL;
    let url = this.data.weaponModel;
    let mirrored = false;

    if (view && model) {
      // Engine.Inventory.CalcDrawOffset: the weapon's origin sits at PlayerViewOffset from
      // the eye, and Engine.Weapon.SetHand multiplies its Y by Hand — every offset Epic
      // wrote is left of centre, and the right hand is the same layout reflected. See the
      // header for why the offset is taken in plain Unreal Units and why it is scaled by
      // the same factor as the mesh.
      const d = view.offsetUU || [0, 0, 0];
      const k = UU_TO_M * VIEW.MODEL_SCALE;
      // UT axes (x forward, y right, z up) -> scene axes (x right, y up, z back).
      x = sign * Math.abs(d[1]) * k;
      y = d[2] * k;
      z = -d[0] * k;
      // Epic's RotOrigin, per weapon. The rebuilt view meshes come out already in view
      // frame and ship [0,0,0]; the older ones carry a real rotation, and both work.
      rot = view.rotationDeg || rot;
      scale = VIEW.MODEL_SCALE;
      muzzleLocal = view.muzzleLocal || [0, 0, 0];
      url = model;
      mirrored = !!mirror;
    }

    slot.position.set(x, y, z);
    slot.rotation.set(rot[0] * DEG, rot[1] * DEG, rot[2] * DEG);
    // A NEGATIVE x scale is the mirror. It costs a material fix (see onSlotReady) because
    // it inverts triangle winding, but it is the only way to reflect a mesh: rotating it
    // 180 degrees turns the gun to face backwards, which an earlier build tried and got an
    // unrecognisable slab for.
    slot.scale.set(mirrored ? -scale : scale, scale, scale);
    slot.visible = !!show;

    this.setSlotMuzzle(slot, muzzleLocal);

    if (slot.userData.slotUrl === url) {
      // Same mesh as before — a respawn, or the second Enforcer arriving. No reload, so
      // the bring-up has to be run directly.
      if (slot.userData.mesh) this.onSlotReady(slot, view, mirrored, playSelect, url);
      return;
    }

    // A different mesh.
    //
    // UT99 plays the outgoing weapon's 'Down' sequence here and waits for it to FINISH
    // before swapping. That is deliberately NOT done, and the manifest's `anims.down` is
    // deliberately not consumed: dressSlot swaps the mesh in the same call, so a Down pose
    // would have exactly zero frames to be seen in. Showing it would mean holding the new
    // weapon back behind an animation while the SERVER already considers you armed with it
    // — a visible lie about what you are shooting. Playing it into a mesh nobody can see
    // would be worse: dead code that looks like a feature.
    if (slot.userData.anim) {
      slot.userData.anim.dispose();
      slot.userData.anim = null;
    }
    slot.userData.slotUrl = url;
    attachModel(slot, url).then(
      ({ root, animations }) => this.onSlotReady(slot, view, mirrored, playSelect, url, root, animations),
      (e) => console.error("[first-person-weapon] Failed to load view model", url, e)
    );
  }

  /** The slot's own barrel tip, rebuilt per weapon because every mesh has its own. */
  setSlotMuzzle(slot, m) {
    let mz = slot.userData.muzzle;
    if (!mz) {
      mz = new THREE.Object3D();
      mz.name = "ut-muzzle-point";
      slot.add(mz);
      slot.userData.muzzle = mz;
    }
    // Stored UNROTATED and UNMIRRORED, in the mesh's own units: this is a child, so it
    // inherits the slot's rotation and scale. That inheritance is also what mirrors it —
    // under scale.x = -S a point at +x lands at -x, which is exactly where the mirrored
    // barrel tip is, so the stored value must NOT be negated as well.
    mz.position.set(m[0], m[1], m[2]);
  }

  /** The slot's model is in: fix the winding, build its mixer, and bring it up. */
  onSlotReady(slot, view, mirrored, playSelect, url, root, animations) {
    if (slot.userData.slotUrl !== url) return; // switched again while this was loading
    const mesh = root || slot.userData.mesh;
    if (!mesh) return;

    if (mirrored) {
      // A negative scale flips the handedness of the transform, so every triangle now
      // winds the other way. three.js already compensates for that on its own — the
      // renderer checks matrixWorld's determinant and swaps the front face — so this is
      // belt and braces against a material that arrives with FrontSide baked in some other
      // way, not the thing that keeps the gun visible. A view weapon is a few hundred
      // triangles a metre from the near plane; drawing both sides costs nothing.
      mesh.traverse((o) => {
        if (!o.isMesh || !o.material) return;
        const mats = Array.isArray(o.material) ? o.material : [o.material];
        for (let i = 0; i < mats.length; i++) {
          if (mats[i] && mats[i].side !== THREE.DoubleSide) {
            mats[i].side = THREE.DoubleSide;
            mats[i].needsUpdate = true;
          }
        }
      });
    }

    if (slot.userData.anim) slot.userData.anim.dispose();
    // The clips arrive beside the model (assets.attachModel returns them) rather than on
    // it, because a cloned scene does not carry its glTF's animations. `anims` absent (an
    // older manifest) leaves the animator with nothing to play: it holds the base pose and
    // every call below is a no-op, which is the old behaviour.
    slot.userData.clips = animations || slot.userData.clips || [];
    slot.userData.anim = createViewAnim(mesh, slot.userData.clips, view && view.anims ? view.anims : null);
    if (slot.userData.anim) {
      if (playSelect) slot.userData.anim.select();
      else slot.userData.anim.idle();
    }

    this.setupMuzzlePosition();
  }

  /** Seconds left on the one-shot fire clip of the gun that fires next (FinishAnim). */
  fireClipBusy() {
    const slot = this.dual && !this.fireLeft ? this.secondSlot : this.primarySlot;
    const anim = slot && slot.userData.anim;
    return anim && anim.fireBusy ? anim.fireBusy() : 0;
  }

  /** Every slot that is currently drawn, primary first. */
  liveSlots() {
    const out = [];
    if (this.primarySlot && this.primarySlot.visible) out.push(this.primarySlot);
    if (this.dual && this.secondSlot && this.secondSlot.visible) out.push(this.secondSlot);
    return out;
  }

  /**
   * Hold a different weapon.
   *
   * The model is UT99's own FIRST-PERSON mesh, with the arm, not the pickup mesh that
   * spins on the floor — and, since this commit, that is true of the Enforcer too. This
   * method used to return early for it (`spec.model` is null: the Enforcer has no floor
   * pickup) and leave index.html's static pickup mesh in your hands, which is precisely
   * why the gun everyone spawns with was the one gun that could not animate.
   *
   * Nothing is created or destroyed here. The slots are permanent nodes and only their
   * model changes, so a weapon you have held before comes back out of the asset cache and
   * the next frame is never racing a GLTF parse.
   */
  setWeapon(id) {
    if (id === this.weaponId) return;
    this.weaponId = id;
    // Warm this weapon's audio now rather than on its first shot, which would otherwise
    // be silent while the file loads — and the first shot with a weapon you just picked
    // up is the one you notice.
    warmSounds(id);
    // A weapon change ends any looped fire animation the last one had running.
    this._loopingFire = false;
    this.refitWeapons(true);
  }

  /**
   * Grant or remove the second Enforcer.
   *
   * Only ever called from a server message (pickup-taken / loadout / death). UT99 gives
   * the pair two DIFFERENT meshes — AutoML in the left hand, AutoMR in the right — and
   * both of them animate, so each slot carries its own AnimationMixer and each shot plays
   * the fire clip on whichever gun's turn it is.
   */
  setDual(dual) {
    if (dual === this.dual) return;
    this.dual = dual;
    this.refitWeapons(true);
    this.game.events.emit("loadout-changed", { dual });
  }

  /**
   * The instant trace: nearest of world geometry and other players wins.
   *
   * One line, now that systems/hitscan.js is the port of the A-Frame hitscan.js. It tests
   * the world's flat mesh list and every remote player's analytic CAPSULE with UT99's
   * headshot sphere on top of it, and reports a surface normal for the decal. The stand-in
   * that lived here traced the avatars' DRAWN TRIANGLES instead — enough to stop a shot at
   * a body, but it had no head and no radial normal — and the world half read a
   * stand-in collider list that hitscan's getWorldColliders() now owns.
   *
   * No `excludeId`: bodies() carries no local body, so there is nothing to exclude the way
   * the A-Frame call site's `excludeEl: #soldier` had to. Same result shape as before.
   */
  traceShot(origin, dir) {
    return traceShot(this.game, origin, dir, { maxDist: this.data.maxRange });
  }

  fireBullet() {
    if (!this.weapon) return;

    // Update muzzle position (world space) — the tracer starts here
    this.setupMuzzlePosition();

    // The trace itself starts at the eye so it agrees with the crosshair; only the
    // visible tracer starts at the muzzle.
    const camera = this.game.camera;
    camera.getWorldPosition(this._rayOrigin);

    // Alternate hands when dual-wielding, so shots visibly leave the left gun and
    // the right gun in turn rather than always the right.
    //
    // The mirror is across the CAMERA'S right axis, not world X: the player can be
    // facing any direction, and reflecting world X would send the left muzzle
    // somewhere arbitrary as soon as they turned. The TRACE is untouched — it still
    // runs from the eye down the crosshair — only where the tracer and flash appear
    // moves, which is the part a player actually reads.
    if (this.dual) {
      this.fireLeft = !this.fireLeft;
      if (this.fireLeft && this.secondSlot) {
        this._right.setFromMatrixColumn(camera.matrixWorld, 0).normalize();
        this._muzzleLocal.copy(this.muzzlePosition).sub(this._rayOrigin);
        const along = this._muzzleLocal.dot(this._right);
        this.muzzlePosition.addScaledVector(this._right, -2 * along);
      }
    }

    // Where the crosshair points. THREE.Camera overrides getWorldDirection to return the
    // FORWARD (-Z) axis already, so unlike the old code — which read it off the camera
    // ENTITY, a plain Object3D whose +Z it had to negate — there is no negate here.
    const dir = this._rayDir;
    camera.getWorldDirection(dir);
    this.applySpread(dir);

    // A PROJECTILE weapon traces nothing. There is no instant hit to find, no tracer to
    // draw down the crosshair and no local-hit to claim: the shot becomes a thing the
    // SERVER flies through the level, and what comes back is a `projectile` message that
    // ut-projectiles draws. Running the hitscan here anyway would put a bullet tracer and
    // a spark on the wall the instant a rocket left the tube.
    if (!weapon(this.weaponId).projectile) {
      // Single instant trace: nearest of world geometry and other players wins, so shots
      // stop at walls instead of passing through them.
      const result = this.traceShot(this._rayOrigin, dir);

      // Everything the shot LOOKS like: for the Shock Rifle a growing ShockBeam and a
      // ring at the far end, for the Enforcer and the Sniper Rifle a tracer plus UT99's
      // wall hit (BulletImpact mesh, smoke puff, sparks, one of its four sounds). And
      // Botpack's two cartridge weapons throw a UT_ShellCase out of the muzzle; the
      // helper ignores every other weapon.
      const fx = this.game.systems.get("ut-effects");
      fx?.drawHitscanShot?.(this.weaponId, this.muzzlePosition, result, this.dual);
      fx?.ejectShell?.(this.weaponId, this.muzzlePosition, dir);

      if (result.type === "player") {
        // Server decides the damage; keep the payload shape other listeners expect.
        this.game.events.emit("local-hit", { victimId: result.playerId, point: result.point });
      }
    }

    // Emit to the network layer — unchanged contract (origin, dir).
    // This is the only shot spawn path now; the old local bullet entity was a duplicate.
    this.game.events.emit("local-fire", {
      origin: {
        x: this.muzzlePosition.x,
        y: this.muzzlePosition.y,
        z: this.muzzlePosition.z,
      },
      dir: {
        x: dir.x,
        y: dir.y,
        z: dir.z,
      },
    });

    // Background music ducks on this; it used to come from the bullet component
    this.game.events.emit("bullet-fired");

    // Feel. Nothing below this line touches the trace, the direction or the payload
    // above — it is the shot as the player SEES and HEARS it, and every part of it is
    // Epic's now rather than tuned here. See the header comment for the three systems.
    this.fireFeel();
  }

  /**
   * Everything a shot does that is not a shot: the gun's animation, the view shake, the
   * screen tint, the 2D muzzle icon, the crosshair bloom and the sound.
   *
   * Read defensively throughout. `view.anims`, `view.shake`, `view.instFlash` and
   * `view.muzzleFlash` are produced by the asset pipeline and any of them may be absent
   * from a given build of src/shared/weapons.js; the fallbacks are, in order, no
   * animation, TournamentWeapon's own default shake, no tint, and no flash.
   */
  fireFeel() {
    const spec = weapon(this.weaponId);
    const view = spec && spec.view ? spec.view : null;

    // 1. The gun animates. On a dual pair only the gun that actually fired does.
    const slot = this.dual && this.fireLeft ? this.secondSlot : this.primarySlot;
    const anim = slot && slot.userData.anim;
    if (anim) {
      // A repeat shot is one fired with the trigger still held from the shot before —
      // UT99 reaches PlayRepeatFiring the same way (NormalFire re-entered with bFire set).
      anim.fire(this.isFiring && (this._burstShots || 0) > 1);
      // Shock and Ripper LoopAnim while the trigger is held; updateViewAnimations stops
      // the loop once the shots stop, and needs to know one is running.
      if (anim.isLoopingFire()) this._loopingFire = true;
    }

    // 2. The view shakes — a roll and a vertical jolt, never the aim. The controller owns
    // both transforms the shake is written to (the camera and gunRoot) and supplies
    // Botpack.TournamentWeapon's default for a weapon with no shake block of its own,
    // which is what every stock weapon that does not override ShakeView actually uses.
    if (this.game.player && this.game.player.shake) this.game.player.shake(view && view.shake);

    // 3. PlayerPawn.ClientInstantFlash — one frame of screen tint in the weapon's own
    // fog colour. Absent for weapons Epic gave none (and for a manifest that predates it).
    const inst = view && view.instFlash;
    if (inst && this.hud) this.hud.instantFlash(inst.scale, inst.fog);

    // 4. Weapon.RenderOverlays' muzzle icon. Enforcer and Sniper Rifle only.
    this.drawMuzzleFlash(view);

    this.crosshairBloom = GAME_CONFIG.WEAPON.CROSSHAIR_BLOOM;
    this.playWeaponSound();
  }

  // Nudge the shot inside a small cone. Random per shot, applied before the trace so the
  // tracer and the networked direction match exactly what was hit.
  applySpread(dir) {
    // Two guns fire twice as fast and half as well. Without this the pickup would
    // be a pure upgrade, and a pure upgrade is not a choice.
    const spread = this.dual ? this.data.spread * GAME_CONFIG.WEAPON.DUAL_SPREAD_MULTIPLIER : this.data.spread;
    if (spread <= 0) return;

    // Build a basis around the shot direction
    this._right.set(0, 1, 0).cross(dir);
    if (this._right.lengthSq() < 1e-6) this._right.set(1, 0, 0);
    this._right.normalize();
    this._up.copy(dir).cross(this._right).normalize();

    const angle = Math.random() * Math.PI * 2;
    const radius = Math.sqrt(Math.random()) * spread;
    dir.addScaledVector(this._right, Math.cos(angle) * radius);
    dir.addScaledVector(this._up, Math.sin(angle) * radius);
    dir.normalize();
  }

  // ---- muzzle flash: Engine.Weapon.RenderOverlays ----
  //
  // What used to be here was a textured quad parented to the camera plus a PointLight at
  // the barrel tip, both fading out over MUZZLE_FLASH_LIFE. UE1 draws neither. It draws
  //
  //     Canvas.Style = 3;                       // STY_Translucent: black is transparent
  //     Canvas.DrawIcon(MFTexture, MuzzleScale)
  //
  // i.e. a 2D ICON on the HUD canvas, for FlashLength seconds, and ONLY on the two
  // weapons that have an MFTexture at all — the Enforcer (which picks one of five at
  // random per shot) and the Sniper Rifle. Shock, Rocket, Ripper and Redeemer have none,
  // and drawing one for them was pure invention.
  //
  // THE ONE DEVIATION, stated plainly: UT99 positions the icon at a fixed SCREEN FRACTION
  // (FlashY / FlashO) that is bound up with handedness bookkeeping this build does not
  // have. Instead the slot's own barrel tip is projected from world space to the screen
  // and the icon is centred there, so the flash tracks the gun through sway, the shake and
  // the left/right hand swap. It sits where the barrel is rather than where Epic's
  // constants put it.
  drawMuzzleFlash(view) {
    const mf = view && view.muzzleFlash;
    if (!mf || !this.hud) return;
    const textures = Array.isArray(mf.textures) ? mf.textures : null;
    if (!textures || !textures.length) return;

    const camera = this.game.camera;
    if (!camera) return;

    // this.muzzlePosition is the world barrel tip fireBullet() has already refreshed,
    // reflected to the other hand if this was the second Enforcer's shot.
    this._screen.copy(this.muzzlePosition).project(camera);
    // Behind the near plane: project() returns nonsense there and the icon would appear
    // mirrored across the centre of the screen.
    if (this._screen.z > 1) return;

    const w = window.innerWidth || 1280;
    const h = window.innerHeight || 720;
    const x = (this._screen.x * 0.5 + 0.5) * w;
    const y = (-this._screen.y * 0.5 + 0.5) * h;
    // FlashS is the texture's drawn size in UT's 640-wide reference viewport, so it scales
    // with the window exactly the way DrawIcon's Canvas.ClipX scaling does.
    const size = (mf.flashS || 128) * (typeof mf.muzzleScale === "number" ? mf.muzzleScale : 1) * (w / 640);
    const tex = textures[Math.floor(Math.random() * textures.length) % textures.length];

    this.hud.muzzleFlash(tex, x, y, size, mf.flashLength);
  }

  // ---- view animations ----
  /**
   * Drive each slot's mixer, and end a looped fire animation once the shooting stops.
   *
   * Only Shock and Ripper LoopAnim while the trigger is held; every other weapon's fire
   * clip is a one-shot that returns itself to the idle when it finishes.
   *
   * BOTH conditions are needed to stop one. The trigger being up is the real signal — it
   * is what ends the Fire state in UnrealScript — but on its own it would cut the last
   * shot's animation off mid-swing, so the 0.1 s grace is added after it. A gap threshold
   * alone would not do either: Shock and Ripper fire every 0.6 s, so any threshold short
   * enough to feel responsive would drop the loop between two shots of a held trigger.
   */
  updateViewAnimations(dt, nowSeconds) {
    // A LoopAnim'd fire runs for the whole of UT99's fire STATE, i.e. the refire window,
    // not just while the button is down: a single click on the Shock Rifle shows a full
    // cycle of 'Fire1' (0.79 s — Epic tuned it to the 0.7 s refire), not 0.1 s of it and
    // then a snap to idle.
    const rate = this.dual ? GAME_CONFIG.WEAPON.DUAL_FIRE_RATE : weapon(this.weaponId).fireRate;
    const loopWindow = Math.max(0.1, 1 / Math.max(0.05, rate));
    if (this._loopingFire && !this.isFiring && nowSeconds - this.lastFireTime > loopWindow) {
      this._loopingFire = false;
      const slots = this.liveSlots();
      for (let i = 0; i < slots.length; i++) {
        if (slots[i].userData.anim) slots[i].userData.anim.stopFire();
      }
    }

    if (this.primarySlot && this.primarySlot.userData.anim) this.primarySlot.userData.anim.update(dt);
    if (this.dual && this.secondSlot && this.secondSlot.userData.anim) this.secondSlot.userData.anim.update(dt);
  }

  // ---- crosshair ----
  // ChallengeHUD.DrawCrossHair does not react to firing at all — the crosshair
  // is nailed to the centre of the screen at a fixed integer scale. The one
  // thing that moves it is a pickup: for 0.4 s afterwards XScale is multiplied
  // by 1+5t while t < 0.2 and by 3-5t after, i.e. it grows to 2x and comes back.
  // `crosshairBloom` is still set by fireBullet() and decayed below, and nothing reads
  // it — not here and not in the A-Frame build. Spread comes from `data.spread` alone.
  // It is kept because it is the hook a future recoil/bloom model would grow from.
  decayCrosshairBloom(dt) {
    if (this.crosshairPulse > 0) {
      this.crosshairPulse = Math.max(0, this.crosshairPulse - dt);
      this.updateCrosshair();
    }
    if (this.crosshairBloom <= 0) return;
    this.crosshairBloom = Math.max(0, this.crosshairBloom - dt * GAME_CONFIG.WEAPON.CROSSHAIR_BLOOM_DECAY);
  }

  /** Start the 0.4 s pickup pulse. */
  pulseCrosshair() {
    this.crosshairPulse = 0.4;
    this.updateCrosshair();
  }

  updateCrosshair() {
    if (!this.crosshair) return;
    const w = window.innerWidth || 1280;
    // XScale = ClipX < 512 ? 0.5 : max(1, int(0.1 + ClipX/640)) — 1 @640,
    // 2 @1280, 3 @1920. Integer steps, so the 64x64 art never lands off-grid.
    let scale = w < 512 ? 0.5 : Math.max(1, Math.trunc(0.1 + w / 640));
    // The pickup pulse rides on top as a pure multiplier, 1 -> 2 -> 1 over 0.4 s.
    const t = 0.4 - this.crosshairPulse; // seconds since the pickup
    if (this.crosshairPulse > 0) scale *= t < 0.2 ? 1 + 5 * t : 3 - 5 * t;
    const px = 64 * scale;
    this.crosshair.style.width = px + "px";
    this.crosshair.style.height = px + "px";
    this.crosshair.style.marginLeft = -px / 2 + "px";
    this.crosshair.style.marginTop = -px / 2 + "px";
  }

  playWeaponSound() {
    playPooledWeaponSound(0.1, weapon(this.weaponId).sound);
  }

  /**
   * The primitive box gun, built only when there is no player controller to hang the real
   * one off — a stripped page or a test harness. It has no view model, no animations and
   * no muzzle child, so the muzzle falls back to `data.muzzleOffset` off the camera and
   * the shake still runs; you can shoot, you just cannot see a UT99 gun.
   */
  createFallbackWeapon() {
    console.log("[first-person-weapon] Creating weapon");

    const group = new THREE.Group();
    group.position.set(this.data.weaponPosition.x, this.data.weaponPosition.y, this.data.weaponPosition.z);
    group.rotation.set(
      this.data.weaponRotation.x * DEG,
      this.data.weaponRotation.y * DEG,
      this.data.weaponRotation.z * DEG
    );
    group.scale.set(this.data.weaponScale.x, this.data.weaponScale.y, this.data.weaponScale.z);

    // Same primitives, dimensions, colours and placements the geometry/material attributes
    // built. A-Frame's cylinder is Y-up with `height` along Y, which is three's own
    // CylinderGeometry, so the two "90 0 0" rotations mean the same thing here.
    const mesh = (geometry, color, metalness, roughness, pos, rotX) => {
      const m = new THREE.Mesh(geometry, new THREE.MeshStandardMaterial({ color, metalness, roughness }));
      m.position.set(pos[0], pos[1], pos[2]);
      if (rotX) m.rotation.x = rotX * DEG;
      group.add(m);
      return m;
    };

    // Main weapon body
    mesh(new THREE.BoxGeometry(0.2, 0.08, 1.2), "#444444", 0.9, 0.1, [0, 0, 0]);
    // Barrel
    mesh(new THREE.CylinderGeometry(0.02, 0.02, 0.8, 16), "#333333", 0.9, 0.1, [0, 0, 0.4], 90);
    // Handle
    mesh(new THREE.BoxGeometry(0.15, 0.3, 0.1), "#555555", 0.7, 0.3, [0, -0.15, -0.3]);
    // Trigger guard
    mesh(new THREE.CylinderGeometry(0.08, 0.08, 0.05, 16), "#444444", 0.9, 0.1, [0, -0.05, -0.2], 90);

    this.held.add(group);
    this.weapon = group;
    this.fallback = group;
    this.setupMuzzlePosition();
    console.log("[first-person-weapon] Weapon created successfully");
  }

  /**
   * Put the gun away. Called on death (health.js flips `enabled` off) and on dispose().
   *
   * HIDES the slots rather than destroying them. They used to be removeChild()'d, and
   * because the primary one is #player-weapon — written in index.html, with the sway
   * settings on it — the FIRST DEATH deleted the real Enforcer from the DOM for the rest
   * of the session. Respawn set `enabled` back to true, setupWeapon() looked for
   * #player-weapon, found nothing, and built the crude primitive fallback instead: every
   * player was holding a grey box from their first death onwards. The slots are ours to
   * build now, not the markup's, but keeping the loaded model still means a respawn
   * re-arms in one frame instead of racing a model load.
   *
   * The shake is reset outright: dying while the view is mid-roll would otherwise leave
   * the death screen sitting at a tilt.
   */
  removeWeapon() {
    if (!this.weapon) return;
    if (this.fallback) {
      this.fallback.removeFromParent();
      this.fallback.traverse((o) => {
        if (o.isMesh) {
          o.geometry.dispose();
          o.material.dispose();
        }
      });
      this.fallback = null;
    }
    if (this.primarySlot) this.primarySlot.visible = false;
    if (this.secondSlot) this.secondSlot.visible = false;
    this.weapon = null;
    this._loopingFire = false;
    if (this.game.player && this.game.player.resetShake) this.game.player.resetShake();
  }

  createTouchFireButton() {
    // Only create on touch devices
    if (!("ontouchstart" in window)) {
      console.log("[first-person-weapon] Not a touch device, skipping fire button");
      return;
    }

    console.log("[first-person-weapon] Creating touch fire button...");

    const fireButton = document.createElement("div");
    fireButton.id = "touch-fire-button";
    fireButton.innerHTML = "FIRE";
    fireButton.style.cssText = `
      position: fixed;
      bottom: 20px;
      right: 20px;
      width: 80px;
      height: 80px;
      background: rgba(60, 60, 60, 0.8);
      border: 3px solid rgba(255, 255, 255, 0.9);
      border-radius: 50%;
      display: flex;
      align-items: center;
      justify-content: center;
      font-size: 14px;
      font-weight: bold;
      color: white;
      cursor: pointer;
      pointer-events: auto;
      user-select: none;
      -webkit-user-select: none;
      -webkit-touch-callout: none;
      -webkit-tap-highlight-color: transparent;
      z-index: 1000;
      touch-action: manipulation;
      transition: all 0.1s ease;
    `;

    // The button reports to engine/input.js like every other input source; update() reads
    // the same `fireHeld` level whether it came from a finger, KeyX or the mouse.
    const press = (down) => {
      this.game.input.pressFire(down);
      fireButton.style.background = down ? "rgba(40, 40, 40, 0.9)" : "rgba(60, 60, 60, 0.8)";
      fireButton.style.transform = down ? "scale(0.95)" : "scale(1)";
    };

    // Touch events
    fireButton.addEventListener(
      "touchstart",
      (e) => {
        e.preventDefault();
        press(true);
      },
      { passive: false }
    );

    fireButton.addEventListener(
      "touchend",
      (e) => {
        e.preventDefault();
        press(false);
      },
      { passive: false }
    );

    fireButton.addEventListener(
      "touchcancel",
      (e) => {
        e.preventDefault();
        press(false);
      },
      { passive: false }
    );

    // Mouse events for desktop testing
    fireButton.addEventListener("mousedown", (e) => {
      e.preventDefault();
      press(true);
    });

    fireButton.addEventListener("mouseup", (e) => {
      e.preventDefault();
      press(false);
    });

    document.body.appendChild(fireButton);
    this.fireButton = fireButton;
  }

  onLocalHit() {
    // Show hitmarker (white X) instead of red flash — only the victim should flash red
    this.showHitmarker();
  }

  showHitmarker() {
    if (!this.hitmarker) return;
    clearTimeout(this._hitmarkerTimer);
    this.hitmarker.style.transition = "none";
    this.hitmarker.style.opacity = "1";
    // Force reflow so the transition kicks in
    void this.hitmarker.offsetWidth;
    this.hitmarker.style.transition = "opacity 150ms ease-out";
    this._hitmarkerTimer = setTimeout(() => {
      this.hitmarker.style.opacity = "0";
    }, 80);
  }

  onLocalKill() {
    const now = Date.now();

    // Check if this is part of a multikill streak
    if (now - this.lastKillTime <= this.data.multikillTimeout) {
      this.killStreak++;
    } else {
      this.killStreak = 1; // Reset streak
    }

    this.lastKillTime = now;
    this.spreeCount++;

    // MultiKillMessage.ClientReceive, switch = kills in the streak - 1. These
    // are the exact strings, spacing and punctuation the class ships; stock
    // UT99 never reaches "Triple Kill!" even though the string exists. Switch 1
    // (Double) is drawn in the Big font, 2 and up in the Huge one.
    if (this.killStreak >= 2) {
      const labels = {
        2: "Double Kill!",
        3: "Multi Kill!",
        4: "ULTRA KILL!!",
      };
      const text = labels[this.killStreak] || "M O N S T E R  K I L L !!!";
      this.showAnnouncement(this.announceEl, text, this.killStreak >= 3 ? "huge" : "big");
    }

    // KillingSpreeMessage — third person, WITH the player's name, at exactly
    // 5/10/15/20/25 kills without dying (DeathMatchPlus.NotifySpree).
    const spreeLabels = {
      5: "is on a killing spree!",
      10: "is on a rampage!",
      15: "is dominating!",
      20: "is unstoppable!",
      25: "is Godlike!",
    };
    if (spreeLabels[this.spreeCount]) {
      let name = "You";
      try {
        if (typeof window.getPlayerName === "function") name = window.getPlayerName() || "You";
      } catch {
        /* the name is a nicety; never let it cost the announcement */
      }
      this.showAnnouncement(this.spreeEl, `${name} ${spreeLabels[this.spreeCount]}`, "big");
    }

    // Play multikill sound based on streak
    this.playMultikillSound(this.killStreak);
  }

  /**
   * A LocalMessage at 0.2552 H. bFadeMessage means DrawColor * remaining /
   * Lifetime — a LINEAR ramp to black over the whole 3 s life, with no fade-in
   * and no scale punch: the line is at full strength on the first frame and
   * only ever gets dimmer. All of that is one CSS animation; this only restarts
   * it, which is also how bIsUnique messages replace each other on a line.
   * @param {HTMLElement} el
   * @param {string} text
   * @param {"big"|"huge"} [size] FontSize 1 -> GetBigFont, 2 -> GetHugeFont
   */
  showAnnouncement(el, text, size) {
    if (!el) return;
    clearTimeout(el._hideTimer);
    el.textContent = text;
    el.dataset.size = size === "huge" ? "huge" : "big";
    el.classList.remove("is-on");
    void el.offsetWidth;
    el.classList.add("is-on");
    el._hideTimer = setTimeout(() => {
      el.classList.remove("is-on");
    }, 3000);
  }

  playMultikillSound(streak) {
    // All streaks currently use the same sound — volume increases with streak
    const volume = Math.min(0.05, 0.01 * streak);
    playPooledWeaponSound(volume, weapon(this.weaponId).sound);
  }

  dispose() {
    for (const off of this._off) off();
    this._off.length = 0;
    if (this._onResize) window.removeEventListener("resize", this._onResize);
    this.removeWeapon();

    // Each slot's AnimationMixer holds a cached clipAction per clip and a reference to
    // the model root; uncacheRoot (inside dispose) is what lets three.js let go of both.
    // There is no GPU state to release here any more — the muzzle flash quad, its texture
    // and its point light are gone, replaced by two DOM overlays the HUD owns.
    for (const slot of this.slots) {
      if (slot && slot.userData.anim) {
        slot.userData.anim.dispose();
        slot.userData.anim = null;
      }
    }
    this.sway.dispose();
    this.held.removeFromParent();
    if (this.hud) {
      this.hud.release();
      this.hud = null;
    }

    // NOTE: the tracer / spark / decal pools are module-global in impact-effects.js, and
    // the beam / ring / smoke / spark / shell pools are module-global in ut-effects.js.
    // Both are shared with network.js, which draws every REMOTE player's shot through the
    // same two entry points. Disposing them here would tear down another consumer's GPU
    // resources (and re-pay the pre-warm cost on the next remote shot). They live as long
    // as the scene does, which is the correct lifetime, so this system disposes neither.

    // Clear any leftover timers
    clearTimeout(this._hitmarkerTimer);

    // Remove the touch fire button and the HUD overlays
    if (this.fireButton) this.fireButton.remove();
    if (this.crosshair) this.crosshair.remove();
    if (this.hitmarker) this.hitmarker.remove();
    if (this.announceEl) this.announceEl.remove();
    if (this.spreeEl) this.spreeEl.remove();
  }
}
