// map-transform.js — the one place the CTF-Face world scale is written down.
//
// This module has ZERO dependencies (no A-Frame, no THREE, no DOM, no Node) so the
// browser game, the AR page and the build-time asset pipeline can all read the same
// number instead of each carrying their own copy of it.
//
// ---------------------------------------------------------------------------
// WHERE THE NUMBER COMES FROM
// ---------------------------------------------------------------------------
// The fan model of CTF-Face in assets/3d/map/ is a UNIFORM scale of the original
// Unreal level, fitted by trimmed least squares of 222 CTF-Face actors (132 nav
// points, 20 PlayerStarts, 2 FlagBases, 56 pickups, 12 teleporters) against the
// navmesh's distance field:
//
//     s     = 0.010062 m per Unreal Unit      (the scale the .gltf was authored at)
//     axes  = scene.x = +UU.x, scene.y = +UU.z, scene.z = +UU.y
//     yaw   = sceneYawDeg = normalize360(-(utYawDeg + 90))
//
// The PLAYER, meanwhile, is authored at UT99 pawn scale: a UT99 pawn is 78 UU tall
// and the Soldier model measures 1.83 m, so the rig lives at 0.0235 m/UU (see
// GAME_CONFIG.MOVEMENT.UU_TO_METRES, and the movement constants derived from it).
//
// The map was therefore 43% of the size the player is built for — CTF-Face's 71 m
// towers read as 30 m, and a flag run that should take ~19 s took ~8. WORLD_SCALE is
// the factor that closes that gap:
//
//     WORLD_SCALE = 0.0235 / 0.010062 = 2.33552
//
// After scaling, the map sits at exactly pawn scale (0.0235 m/UU) and the UU->scene
// transform becomes:
//
//     scene = [ 0.0235*uu.x - 51.2937 , 0.0235*uu.z + 46.4147 , 0.0235*uu.y - 5.3047 ]
//
// The fit carries about +/-5% of scale uncertainty and ~2 degrees of relative yaw
// between the two towers, so treat WORLD_SCALE as good to a couple of percent, not to
// five decimals. It is written down once, here, precisely so it can be revised.
//
// ---------------------------------------------------------------------------
// HOW IT IS APPLIED
// ---------------------------------------------------------------------------
// It is BAKED INTO THE GEOMETRY, not set as an entity `scale` attribute:
// scripts/optimize-assets.mjs multiplies the root-node transform of the map and the
// navmesh by WORLD_SCALE on its way to assets-optimized/. The `world` and `navmesh` nodes
// src/game/scene/world.js builds therefore stay at the identity transform, the contract
// src/ar/config/ar-config.js documents and src/ar/three/players.js depends on (it
// drops raw server pose coordinates straight into the map-model's node).
//
// Every world-anchored constant in the repo — flag homes, spawns, pickup positions,
// map bounds, light positions and ranges, shadow frustum, camera heights, trace
// ranges — has already been multiplied through by this factor and is stored in its
// final, scaled form. PLAYER-anchored values (eye height, hitbox, speeds, jump,
// gravity, recoil, weapon offsets, prop sizes) were deliberately NOT scaled: the
// player did not change size, the world did.
//
// The transform itself is below, and src/shared/map-actors.js — generated by
// scripts/gen-map-actors.mjs from Epic's own actor table — is where the flag bases,
// the twenty PlayerStarts, the tower roofs and the pickup spots come out of it. Nothing
// downstream should be re-deriving a world position by hand any more.
export const WORLD_SCALE = 2.33552;

// ---------------------------------------------------------------------------
// THE MEASURED BASIS  (stage (b): the actual UU -> scene transform)
// ---------------------------------------------------------------------------
// Fitted by trimmed least squares of 222 CTF-Face actors (132 nav points, 20
// PlayerStarts, 2 FlagBases, 56 pickups, 12 teleporters) against the navmesh, as a
// similarity transform. Three models were tried; the uniform, zero-yaw one won on
// simplicity at almost no cost (trimmed RMS 0.325 vs 0.249 scene units for the best
// anisotropic+yaw variant, which wanted sv/s = 0.942 and -0.77 deg). So the fan model
// really is a plain uniform scale of Epic's level, not a redrawn approximation.
//
//   AS AUTHORED (what the .gltf in assets/3d/ is drawn at):
//     s      = 0.010062 m/UU
//     offset = (-21.963093, 19.873278, -2.271319)
//     axes   = scene.x = +UU.x,  scene.y = +UU.z (up),  scene.z = +UU.y
//     yaw    = sceneYawDeg = normalize(-(utYawDeg + 90))
//
// UT is left-handed (X forward, Y right, Z up); three.js is right-handed and Y-up.
// Mapping +UU.y -> +scene.z absorbs the handedness flip, which is why there is no axis
// negation anywhere below and why the yaw rule needs the leading minus.
//
// Residuals, in scene units at the AUTHORED scale: PlayerStarts mean 0.108 / median
// 0.086, FlagBases mean 0.354, teleporters median 0.385, pickups median 0.52 (mean
// 1.495 — the pickups inside the tower alcoves are the worst-fitting class, because the
// fan model simplified those interiors). Multiply by WORLD_SCALE for the error at play
// scale. Treat a converted position as good to ~1 unit vertically indoors, better than
// that outdoors, and NOT as a surveyed point: anything that has to sit exactly on a
// walkable surface should take x/z from here and snap y to the surface it belongs to.
export const AUTHORED_UU_TO_M = 0.010062;
export const AUTHORED_OFFSET = Object.freeze({ x: -21.963093, y: 19.873278, z: -2.271319 });

// ...and after scripts/optimize-assets.mjs has multiplied the map + navmesh root nodes
// by WORLD_SCALE, which is the geometry the game actually loads. Derived rather than
// re-stated so the two can never drift: scaling the geometry about the scene origin
// scales the offset with it.
//
//   UU_TO_M  = 0.010062 * 2.33552 = 0.0235 m/UU exactly, i.e. UT99 pawn scale
//   OFFSET   = (-51.2952, 46.4151, -5.3047)
export const UU_TO_M = AUTHORED_UU_TO_M * WORLD_SCALE;
export const OFFSET = Object.freeze({
  x: AUTHORED_OFFSET.x * WORLD_SCALE,
  y: AUTHORED_OFFSET.y * WORLD_SCALE,
  z: AUTHORED_OFFSET.z * WORLD_SCALE,
});

/**
 * One Unreal Unit position from CTF-Face, in the coordinates the running game uses.
 *
 * Takes UT's own axis order (x forward, y right, z UP) and returns three.js's
 * (x right, y UP, z back). Pass an actor's `location` straight in:
 *
 *   uuToScene(6488.14, 438.625, -1956.936)  ->  { x: 101.17, y: 0.43, z: 5.0 }
 */
export function uuToScene(x, y, z) {
  return {
    x: UU_TO_M * x + OFFSET.x,
    y: UU_TO_M * z + OFFSET.y,
    z: UU_TO_M * y + OFFSET.z,
  };
}

/** UT stores rotations as 16-bit units, 65536 to the turn. Actor tables carry both. */
export function utYawUnitsToDeg(units) {
  return (units * 360) / 65536;
}

/**
 * Heading, UT degrees -> scene degrees, normalised to [0, 360).
 *
 * The -90 is the axis map: UT's yaw 0 points along +UU.x, which lands on +scene.x,
 * and a three.js object with rotation.y = 0 faces -scene.z. The leading minus is the
 * handedness flip. Sanity check against the real level: CTF-Face's red PlayerStarts sit
 * at utYaw 179.52 -> 90.48 deg, and three's forward is (-sin ry, 0, -cos ry), so they
 * look down -x — out of the red base, towards blue. The blue starts (utYaw 352.09 ->
 * 277.91) look the other way. That is exactly how the map plays.
 */
export function utYawToSceneDeg(utYawDeg) {
  return (((-(utYawDeg + 90)) % 360) + 360) % 360;
}

/** Same heading as a three.js rotation.y, normalised to (-PI, PI] so it reads small. */
export function utYawToSceneRad(utYawDeg) {
  const deg = utYawToSceneDeg(utYawDeg);
  return ((deg > 180 ? deg - 360 : deg) * Math.PI) / 180;
}
