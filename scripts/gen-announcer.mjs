#!/usr/bin/env node
// gen-announcer.mjs — the announcer's rules, for both processes, from one source.
//
//   node scripts/gen-announcer.mjs          # rewrite src/shared/announcer.js + server/announcer-rules.js
//   node scripts/gen-announcer.mjs --check  # fail if out of date
//
// The SERVER decides when the announcer speaks, because the server is the only thing that
// knows who killed whom and when. The CLIENT only plays what it is told. Both need the
// same list of sounds — one to name them, one to preload them — so one table writes both,
// the same arrangement as the weapon table and the character roster.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, "..");
const OUT_SHARED = path.join(ROOT, "src", "shared", "announcer.js");
const OUT_SERVER = path.join(ROOT, "server", "announcer-rules.js");
const CHECK = process.argv.includes("--check");

const DATA = JSON.parse(
  fs.readFileSync(path.join(ROOT, "scripts", "data", "ut-sounds.json"), "utf8"),
).announcer;

const every = [
  DATA.firstBlood,
  ...DATA.multiKill,
  ...DATA.spree,
  DATA.match.start,
  DATA.match.won,
  DATA.match.lost,
  DATA.capture,
  DATA.headshot,
];

const header = `// GENERATED by scripts/gen-announcer.mjs — DO NOT EDIT.
//
// UT99's announcer, and the rules for when it speaks. Every rule below was read out of
// Botpack's own UnrealScript rather than remembered:
//
//   FIRST BLOOD   DeathMatchPlus guards it with a bFirstBlood flag — once a match, on
//                 the first kill, and everybody hears it.
//
//   MULTI-KILL    DeathMessagePlus:
//                     if (Level.TimeSeconds - LastKillTime < ${(DATA.multiKillWindowMs / 1000).toFixed(0)}) MultiLevel++;
//                     else MultiLevel = 0;
//                 so it is a ${(DATA.multiKillWindowMs / 1000).toFixed(0)}-second window between kills, not a count. Level 1 is
//                 ${DATA.multiKill[0]}, 2 is ${DATA.multiKill[1]}, 3 is ${DATA.multiKill[2]}, and 4 or more is
//                 ${DATA.multiKill[3]}. It goes to the KILLER alone, not the room.
//
//   SPREE         DeathMatchPlus calls NotifySpree once a spree passes 4, and NotifySpree
//                 speaks at EXACTLY ${DATA.spreeAt.join(", ")} — every other number returns
//                 without a word. Dying resets it. Everybody hears it.
//
// megakill and triplekill are in Announcer.uax and are deliberately absent: UT99's own
// MultiKillMessage never reaches for them.
`;

const body = `
/** Where the files live. The key IS the file name. */
const ANNOUNCER_DIR = ${JSON.stringify(DATA.dir)};

/** Every sound, for preloading. */
const ANNOUNCEMENTS = ${JSON.stringify(every)};

const FIRST_BLOOD = ${JSON.stringify(DATA.firstBlood)};
const MULTI_KILL = ${JSON.stringify(DATA.multiKill)};
const MULTI_KILL_WINDOW_MS = ${DATA.multiKillWindowMs};
const SPREE_AT = ${JSON.stringify(DATA.spreeAt)};
const SPREE = ${JSON.stringify(DATA.spree)};
const MATCH = ${JSON.stringify(DATA.match)};
const CAPTURE = ${JSON.stringify(DATA.capture)};
const HEADSHOT = ${JSON.stringify(DATA.headshot)};

/** The file for a key, or null if it is not one of ours. */
function announcementUrl(key) {
  return ANNOUNCEMENTS.includes(key) ? \`\${ANNOUNCER_DIR}/\${key}.mp3\` : null;
}

/**
 * What a killer has just earned by killing again, or null.
 *
 * \`level\` is their MultiLevel AFTER incrementing — 1 for the second kill inside the
 * window. Anything past the end of the list stays on the last one, which is how UT99
 * folds every switch from 4 to 9 onto MonsterKill.
 */
function multiKillSound(level) {
  if (level < 1) return null;
  return MULTI_KILL[Math.min(level, MULTI_KILL.length) - 1];
}

/** The spree sound for an exact count, or null. UT99 speaks at those numbers and no others. */
function spreeSound(count) {
  const i = SPREE_AT.indexOf(count);
  return i < 0 ? null : SPREE[i];
}
`;

const shared = `${header}${body}
export {
  ANNOUNCER_DIR,
  ANNOUNCEMENTS,
  FIRST_BLOOD,
  MULTI_KILL_WINDOW_MS,
  MATCH,
  CAPTURE,
  HEADSHOT,
  announcementUrl,
  multiKillSound,
  spreeSound,
};
`;

const server = `${header}${body}
module.exports = {
  ANNOUNCER_DIR,
  ANNOUNCEMENTS,
  FIRST_BLOOD,
  MULTI_KILL_WINDOW_MS,
  MATCH,
  CAPTURE,
  HEADSHOT,
  announcementUrl,
  multiKillSound,
  spreeSound,
};
`;

if (CHECK) {
  const stale = [
    [OUT_SHARED, shared],
    [OUT_SERVER, server],
  ].filter(([f, want]) => (fs.existsSync(f) ? fs.readFileSync(f, "utf8") : "") !== want);
  if (stale.length) {
    console.error(
      `${stale.map(([f]) => path.relative(ROOT, f)).join(", ")} out of date — run: node scripts/gen-announcer.mjs`,
    );
    process.exit(1);
  }
  console.log("announcer table is up to date.");
  process.exit(0);
}
fs.writeFileSync(OUT_SHARED, shared);
fs.writeFileSync(OUT_SERVER, server);
console.log(`wrote the announcer table — ${every.length} lines`);
