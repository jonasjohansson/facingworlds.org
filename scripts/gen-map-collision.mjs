#!/usr/bin/env node
// gen-map-collision.mjs — bake the map mesh into something the SERVER can shoot rays at.
//
//   node scripts/gen-map-collision.mjs          # rewrite server/map-collision.js
//   node scripts/gen-map-collision.mjs --check  # fail if it is out of date
//
// ---------------------------------------------------------------------------
// WHY
// ---------------------------------------------------------------------------
// The server has known where the FLOOR is since navmesh-surface.js. It has never known
// where the WALLS are, and server/bots.js says so in as many words: canSee "knows floors,
// not walls". That was survivable while every shot was hitscan and resolved on the
// client. It is not survivable for a rocket, which is a thing the server moves through
// the level over half a second and which must stop when it reaches a tower.
//
// The whole map is 3,240 triangles. That is small enough to keep all of them — walls
// included, which is the entire point — and raycast directly, with no BVH and no
// approximation. The navmesh keeps its own job: this answers "what is in the way",
// navmesh-surface answers "what am I standing on".
//
// INPUT  assets/3d/map/FacingWorlds_tex_5.gltf, times WORLD_SCALE, exactly as
//        gen-navmesh-surface.mjs reads it for its patch layer.
// OUTPUT server/map-collision.js
//
// Do not hand-edit the output.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadNavmesh } from "./lib/navmesh.mjs";
import { WORLD_SCALE } from "../src/shared/map-transform.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, "..");
const INPUT = path.join(ROOT, "assets", "3d", "map", "FacingWorlds_tex_5.gltf");
const OUTPUT = path.join(ROOT, "server", "map-collision.js");
const CHECK = process.argv.includes("--check");

// Plan-space bucket size. The same 6 units gen-navmesh-surface.mjs uses, for the same
// reason: it keeps the average bucket to a handful of triangles. A ray walks the cells it
// crosses rather than testing all 3,240.
const CELL = 6;

const r3 = (n) => Math.round(n * 1000) / 1000;

const mesh = loadNavmesh(INPUT, WORLD_SCALE);
const tris = [];
let degenerate = 0;
for (const t of mesh.tris) {
  const { a, b, c } = t;
  // A zero-area triangle can never be hit and would divide by zero in the intersection
  // test's determinant.
  const ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2];
  const vx = c[0] - a[0], vy = c[1] - a[1], vz = c[2] - a[2];
  const nx = uy * vz - uz * vy;
  const ny = uz * vx - ux * vz;
  const nz = ux * vy - uy * vx;
  if (Math.hypot(nx, ny, nz) < 1e-9) {
    degenerate++;
    continue;
  }
  tris.push([a, b, c]);
}

let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity, minZ = Infinity, maxZ = -Infinity;
for (const t of tris) {
  for (const v of t) {
    minX = Math.min(minX, v[0]); maxX = Math.max(maxX, v[0]);
    minY = Math.min(minY, v[1]); maxY = Math.max(maxY, v[1]);
    minZ = Math.min(minZ, v[2]); maxZ = Math.max(maxZ, v[2]);
  }
}
const cols = Math.ceil((maxX - minX) / CELL) + 1;
const rows = Math.ceil((maxZ - minZ) / CELL) + 1;

// Bucket by the plan-space cells each triangle's footprint covers.
const buckets = new Array(cols * rows);
let entries = 0;
tris.forEach((t, i) => {
  const x0 = Math.floor((Math.min(t[0][0], t[1][0], t[2][0]) - minX) / CELL);
  const x1 = Math.floor((Math.max(t[0][0], t[1][0], t[2][0]) - minX) / CELL);
  const z0 = Math.floor((Math.min(t[0][2], t[1][2], t[2][2]) - minZ) / CELL);
  const z1 = Math.floor((Math.max(t[0][2], t[1][2], t[2][2]) - minZ) / CELL);
  for (let z = z0; z <= z1; z++) {
    for (let x = x0; x <= x1; x++) {
      const k = z * cols + x;
      (buckets[k] ||= []).push(i);
      entries++;
    }
  }
});
const occupied = buckets.filter(Boolean).length;

const flat = [];
for (const t of tris) for (const v of t) flat.push(r3(v[0]), r3(v[1]), r3(v[2]));

const wrap = (nums, per) => {
  const out = [];
  for (let i = 0; i < nums.length; i += per) out.push("  " + nums.slice(i, i + per).join(", "));
  return out.join(",\n");
};

const body = `// GENERATED by scripts/gen-map-collision.mjs — DO NOT EDIT.
//
// WHAT IS IN THE WAY. Every triangle of the map mesh, walls included, so the server can
// ask where a ray stops. navmesh-surface.js answers the other question — what a body is
// standing on — and deliberately keeps only level ground; this keeps everything.
//
// ${tris.length} triangles${degenerate ? `, ${degenerate} degenerate dropped` : ""}, indexed into a ${cols}x${rows} plan grid of ${CELL}-unit cells
// (${occupied} of ${cols * rows} cells occupied, ${(entries / occupied).toFixed(1)} triangles per occupied cell on average).
// A ray walks only the cells it crosses, so a shot across the map tests a few dozen
// triangles rather than all ${tris.length}.
//
// Extents  x ${r3(minX)}..${r3(maxX)}  y ${r3(minY)}..${r3(maxY)}  z ${r3(minZ)}..${r3(maxZ)}

const MIN_X = ${r3(minX)};
const MIN_Z = ${r3(minZ)};
const COLS = ${cols};
const ROWS = ${rows};
const CELL = ${CELL};

// Nine numbers per triangle: ax, ay, az, bx, by, bz, cx, cy, cz.
const T = [
${wrap(flat, 9)}
];

const GRID = [
${buckets.map((b, i) => (b ? `  [${i}, ${b.join(", ")}]` : null)).filter(Boolean).join(",\n")}
];

// GRID above is a sparse list of [cellIndex, ...triangleIndices]; expand it once at load.
const CELLS = new Array(COLS * ROWS);
for (const row of GRID) CELLS[row[0]] = row.slice(1);

/** Möller–Trumbore, single-sided off, returning the ray parameter or -1. */
function hitTri(i, ox, oy, oz, dx, dy, dz) {
  const o = i * 9;
  const ax = T[o], ay = T[o + 1], az = T[o + 2];
  const e1x = T[o + 3] - ax, e1y = T[o + 4] - ay, e1z = T[o + 5] - az;
  const e2x = T[o + 6] - ax, e2y = T[o + 7] - ay, e2z = T[o + 8] - az;
  const px = dy * e2z - dz * e2y;
  const py = dz * e2x - dx * e2z;
  const pz = dx * e2y - dy * e2x;
  const det = e1x * px + e1y * py + e1z * pz;
  // Two-sided on purpose: a rocket fired from inside a wall's back face should still
  // stop at it, and the map mesh's winding is not something this file gets to trust.
  if (det > -1e-9 && det < 1e-9) return -1;
  const inv = 1 / det;
  const tx = ox - ax, ty = oy - ay, tz = oz - az;
  const u = (tx * px + ty * py + tz * pz) * inv;
  if (u < -1e-6 || u > 1 + 1e-6) return -1;
  const qx = ty * e1z - tz * e1y;
  const qy = tz * e1x - tx * e1z;
  const qz = tx * e1y - ty * e1x;
  const v = (dx * qx + dy * qy + dz * qz) * inv;
  if (v < -1e-6 || u + v > 1 + 1e-6) return -1;
  return (e2x * qx + e2y * qy + e2z * qz) * inv;
}

function normalOf(i, out) {
  const o = i * 9;
  const ux = T[o + 3] - T[o], uy = T[o + 4] - T[o + 1], uz = T[o + 5] - T[o + 2];
  const vx = T[o + 6] - T[o], vy = T[o + 7] - T[o + 1], vz = T[o + 8] - T[o + 2];
  let nx = uy * vz - uz * vy;
  let ny = uz * vx - ux * vz;
  let nz = ux * vy - uy * vx;
  const len = Math.hypot(nx, ny, nz) || 1;
  out.nx = nx / len;
  out.ny = ny / len;
  out.nz = nz / len;
}

// One stamp array reused across calls so a triangle spanning several cells is tested
// once per ray without allocating a Set every time.
const STAMP = new Int32Array(${tris.length});
let stampGen = 0;

/**
 * The first thing a ray meets, or null.
 *
 * Returns { t, x, y, z, nx, ny, nz } — the distance along a UNIT direction, the point,
 * and the surface normal, which is what a bouncing projectile needs.
 */
function raycast(ox, oy, oz, dx, dy, dz, maxDist) {
  const len = Math.hypot(dx, dy, dz);
  if (!(len > 0) || !(maxDist > 0)) return null;
  dx /= len; dy /= len; dz /= len;
  stampGen++;

  let best = maxDist;
  let bestTri = -1;

  // Walk the plan grid cell by cell (a DDA), nearest first, and stop as soon as the
  // closest hit found is nearer than the cell boundary being stepped over.
  let cx = Math.floor((ox - MIN_X) / CELL);
  let cz = Math.floor((oz - MIN_Z) / CELL);
  const stepX = dx > 0 ? 1 : dx < 0 ? -1 : 0;
  const stepZ = dz > 0 ? 1 : dz < 0 ? -1 : 0;
  const tDeltaX = stepX === 0 ? Infinity : Math.abs(CELL / dx);
  const tDeltaZ = stepZ === 0 ? Infinity : Math.abs(CELL / dz);
  const bx = MIN_X + (cx + (stepX > 0 ? 1 : 0)) * CELL;
  const bz = MIN_Z + (cz + (stepZ > 0 ? 1 : 0)) * CELL;
  let tMaxX = stepX === 0 ? Infinity : (bx - ox) / dx;
  let tMaxZ = stepZ === 0 ? Infinity : (bz - oz) / dz;

  for (let guard = 0; guard < COLS + ROWS + 4; guard++) {
    if (cx >= 0 && cx < COLS && cz >= 0 && cz < ROWS) {
      const bucket = CELLS[cz * COLS + cx];
      if (bucket) {
        for (let n = 0; n < bucket.length; n++) {
          const i = bucket[n];
          if (STAMP[i] === stampGen) continue;
          STAMP[i] = stampGen;
          const t = hitTri(i, ox, oy, oz, dx, dy, dz);
          if (t > 1e-5 && t < best) {
            best = t;
            bestTri = i;
          }
        }
      }
    }
    const next = Math.min(tMaxX, tMaxZ);
    if (next > best || next > maxDist) break;
    if (tMaxX < tMaxZ) {
      cx += stepX;
      tMaxX += tDeltaX;
    } else {
      cz += stepZ;
      tMaxZ += tDeltaZ;
    }
    if (stepX === 0 && stepZ === 0) break; // a straight-up or straight-down ray
  }

  if (bestTri < 0) return null;
  const out = { t: best, x: ox + dx * best, y: oy + dy * best, z: oz + dz * best, nx: 0, ny: 0, nz: 0 };
  normalOf(bestTri, out);
  return out;
}

/** Is there anything solid between these two points? */
function blocked(ax, ay, az, bx, by, bz) {
  const dx = bx - ax, dy = by - ay, dz = bz - az;
  const dist = Math.hypot(dx, dy, dz);
  if (!(dist > 0)) return false;
  // Stop just short of the far end so a target standing ON a surface is not occluded by
  // the surface it is standing on.
  return raycast(ax, ay, az, dx, dy, dz, dist - 0.05) !== null;
}

const BOUNDS = { minX: ${r3(minX)}, maxX: ${r3(maxX)}, minY: ${r3(minY)}, maxY: ${r3(maxY)}, minZ: ${r3(minZ)}, maxZ: ${r3(maxZ)} };

module.exports = { raycast, blocked, BOUNDS, TRIANGLE_COUNT: ${tris.length}, CELL };
`;

if (CHECK) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
  if (current !== body) {
    console.error(`${path.relative(ROOT, OUTPUT)} is out of date — run npm run gen:map-collision`);
    process.exit(1);
  }
  console.log(`${path.relative(ROOT, OUTPUT)} is up to date.`);
} else {
  fs.writeFileSync(OUTPUT, body);
  console.log(
    `wrote ${path.relative(ROOT, OUTPUT)} — ${tris.length} triangles, ${(body.length / 1024).toFixed(0)} KB`,
  );
  console.log(`  grid ${cols}x${rows} of ${CELL}  ${occupied} occupied cells, ${(entries / occupied).toFixed(1)} tris each`);
}
